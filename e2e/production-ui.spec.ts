import { test, expect } from '@playwright/test';
import { expectCleanProductUI } from './production-ui-assertions';

test('local authentication, invitations and product settings remain available without development controls', async ({ page }, info) => {
  await page.goto('/');
  await expect(page.getByRole('button', { name: 'Sign in', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Join Haven', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Create your account', exact: true })).toBeVisible();
  await expectCleanProductUI(page);
  await page.screenshot({ path: info.outputPath('auth-desktop.png') });
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(page.getByRole('button', { name: 'Join a community', exact: true })).toBeVisible();
  await expectCleanProductUI(page);
  await page.screenshot({ path: info.outputPath('auth-mobile.png') });
  await page.setViewportSize({ width: 1440, height: 940 });
  const response = await page.request.post('/api/auth/register', { data: { username: `cleanup_${Date.now()}`, password: 'Cleanup-test-password-2026' } });
  expect(response.status()).toBe(201);
  const community = await page.request.post('/api/servers', { data: { name: 'Clean UI community' } });
  expect(community.status()).toBe(201);
  await page.reload();
  await page.getByRole('button', { name: 'Clean UI community', exact: true }).click();
  await expectCleanProductUI(page);
  await page.getByRole('button', { name: 'Lounge', exact: true }).click();
  await expect(page.getByText('Voice connected', { exact: true })).toBeVisible();
  const quality = page.getByRole('button', { name: /^Voice connection:/ });
  await quality.hover();
  await expect(page.getByRole('tooltip')).toBeVisible();
  await quality.focus();
  await expect(page.getByRole('tooltip')).toBeVisible();
  await page.getByRole('button', { name: 'Settings', exact: true }).click();
  await expectCleanProductUI(page);
  await page.screenshot({ path: info.outputPath('settings-profile.png') });
  await page.getByRole('button', { name: 'voice & video', exact: true }).click();
  await expect(page.getByLabel('Input device', { exact: true })).toBeVisible();
  await expect(page.getByRole('option', { name: 'Enhanced · RNNoise', exact: true })).toHaveCount(1);
  await expect(page.getByRole('region', { name: 'Microphone test', exact: true }).getByRole('button', { name: "Let's Check", exact: true })).toBeVisible();
  await page.screenshot({ path: info.outputPath('settings-audio.png') });
  await page.getByRole('button', { name: 'desktop & gaming', exact: true }).click();
  await expect(page.getByLabel('Low-resource gaming mode', { exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Push-to-talk shortcut', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Close dialog', exact: true }).click();
  await page.getByRole('button', { name: 'Join a server', exact: true }).click();
  await page.getByLabel('Invite Code or Link', { exact: true }).fill('https://another-haven.example/invite/abcdef123');
  await expect(page.getByRole('alert')).toContainText('This invitation belongs to a different Haven service');
  await expectCleanProductUI(page);
});
